package com.company.attendance.worker.entity;

/**
 * Enumeration of construction worker designations.
 *
 * <p>Each value represents a distinct trade or role on a
 * construction site, used for classification and wage management.</p>
 */
public enum Designation {

    /** Bricklayer / mason. */
    MASON,

    /** Electrical work specialist. */
    ELECTRICIAN,

    /** Plumbing and pipefitting specialist. */
    PLUMBER,

    /** On-site supervisor overseeing workers. */
    SUPERVISOR,

    /** General construction helper / labourer. */
    HELPER
}
